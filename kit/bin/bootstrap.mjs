#!/usr/bin/env node
// Bootstrap the retrieval substrate on any docs tree:
//   1. insert the Status:/Since:/Answers: header block after each doc's H1
//      (only where missing — never overwrites), and
//   2. regenerate the INDEX from what it finds.
//
//   node kit/bin/bootstrap.mjs [--config <file>] [--apply] [--hook]
//
// The one human step it cannot do for you: phrasing each `Answers:` cell as
// the question that doc answers (question-shaped on purpose — it is what the
// retriever matches against). TODO cells are printed so you can find them.
import { readFileSync, writeFileSync, readdirSync, existsSync, chmodSync } from 'node:fs'
import { join, relative, dirname, basename } from 'node:path'
import { loadConfig } from '../lib/config.mjs'
import { makeArgs } from '../lib/cli.mjs'

const { arg, has } = makeArgs(process.argv.slice(2))
const APPLY = has('apply')
const cfg = loadConfig(arg('config'))
const VOCAB_NOTE = 'open | done | decided | falsified | superseded | reference'

function walk(dir, out = []) {
  if (!existsSync(dir)) return out
  const skip = new Set(['readme.md', basename(cfg.indexPath).toLowerCase()])
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name)
    if (e.isDirectory()) walk(p, out)
    else if (e.name.endsWith('.md') && !skip.has(e.name.toLowerCase())) out.push(p)
  }
  return out
}

const dirs = [cfg.docsDir, ...cfg.archiveDirs].filter(Boolean)
const docs = dirs.flatMap((d) => walk(d))
const rows = []
let inserted = 0, todos = 0

for (const abs of docs) {
  const rel = relative(cfg.corpusRoot, abs)
  const text = readFileSync(abs, 'utf8')
  const lines = text.split('\n')
  const hasStatus = lines.some((l) => /^Status: \S/.test(l) && !l.startsWith('Status: **'))
  const h1 = lines.findIndex((l) => l.startsWith('# ') || /^<h1[\s>]/i.test(l))
  let status = 'open', since = new Date().toISOString().slice(0, 10), answers = '(todo — the question this doc answers)'
  const pick = (re) => text.split('\n').find((l) => re.test(l))?.replace(re, '') ?? ''
  if (hasStatus) {
    status = pick(/^Status: /).split('—')[0].trim().split(/\s+/)[0]
    since = pick(/^Since: /) || since
    answers = pick(/^Answers: /) || answers
  } else {
    // No heading anchor: the header block goes at the top of the file.
    lines.splice(h1 < 0 ? 0 : h1 + 1, 0, ...(h1 < 0 ? [`Status: ${status}`, `Since: ${since}`, `Answers: ${answers}`, ''] : ['', `Status: ${status}`, `Since: ${since}`, `Answers: ${answers}`]))
    inserted++
    console.log(`${APPLY ? 'APPLY' : 'DRY  '} ${rel}  → ${status} (fill the Answers: cell)`)
    if (APPLY) writeFileSync(abs, lines.join('\n'))
  }
  if (answers.startsWith('(todo')) todos++
  const name = abs.split('/').pop()
  const docsRel = relative(cfg.corpusRoot, cfg.docsDir) || 'docs'
  const href = rel.startsWith(docsRel + '/') ? rel.slice(docsRel.length + 1) : rel
  rows.push(`| [\`${name}\`](${href}) | ${status} | ${since} | ${answers} |`)
}

const index = `# docs/INDEX — every work document, one row each

Generated by \`kit/bin/bootstrap.mjs\`; \`kit/bin/manifest-check.mjs\` enforces
that headers and this index agree. Retrieval contract: match your question
against **Answers**, then read that one file. **Status** is from the closed
vocabulary \`${VOCAB_NOTE}\`; the tail after an em-dash is nuance (in the
header, omitted here).

| Doc | Status | Since | Answers |
|---|---|---|---|
${rows.join('\n')}
`
const indexAt = cfg.indexPath
{
  // Case-insensitive filesystems make INDEX.md and index.md the same file —
  // never clobber an existing document that we did not generate.
  const dir = dirname(indexAt)
  const clash = existsSync(dir) && readdirSync(dir).find((f) => f.toLowerCase() === basename(indexAt).toLowerCase())
  if (clash && !readFileSync(join(dir, clash), 'utf8').includes('Generated by `kit/bin/bootstrap.mjs`')) {
    console.error(`refusing to overwrite ${join(dir, clash)} — it is not a generated index.`)
    console.error('  Move that file, or set a different indexPath in the config.')
    process.exit(1)
  }
}
if (APPLY) {
  writeFileSync(indexAt, index)
  console.log(`\nApplied ${inserted} header(s); wrote ${cfg.indexPath} (${rows.length} rows).`)
} else {
  console.log(`\nDry run: ${inserted} header(s) pending; index would have ${rows.length} rows.`)
}
if (todos) console.log(`${todos} Answers: cell(s) still say (todo — …) — each needs one human sentence.`)

if (has('hook')) {
  const hookDir = join(cfg.corpusRoot, '.githooks')
  const hook = join(hookDir, 'pre-commit')
  const line = `node kit/bin/manifest-check.mjs || exit 1`
  let body = existsSync(hook) ? readFileSync(hook, 'utf8') : '#!/bin/sh\n'
  if (!body.includes('manifest-check')) body += `\n${line}\n`
  writeFileSync(hook, body)
  chmodSync(hook, 0o755)
  console.log(`pre-commit hook installed (${hook}) — run: git config core.hooksPath .githooks`)
}
